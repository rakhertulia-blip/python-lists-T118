# Задание 1: Прочитайте маршрут

cities = ["Алматы", "Тараз", "Астана", "Семей"]

# --- 1. Проверка результатов ---
print("cities[0]:", cities[0])        # Алматы
print("cities[-1]:", cities[-1])      # Семей
print("cities[1:3]:", cities[1:3])    # ['Тараз', 'Астана']
print("len(cities):", len(cities))    # 4

# --- 2. Объяснение ошибок и срезов ---

# Почему cities[4] вызывает ошибку (IndexError):
# В списке 4 элемента, их индексы: 0, 1, 2, 3.
# Индекса 4 не существует, поэтому Python генерирует ошибку IndexError: list index out of range.
try:
    print(cities[4])
except IndexError as e:
    print("\Ошибка при cities[4]:", e)

# Почему cities[4:] НЕ вызывает ошибку:
# Механизм срезов (slice) в Python защищен от выхода за границы.
# Если указать начальный индекс за пределами списка, Python просто вернет пустой список [].
print("Срез cities[4:]:", cities[4:])  # []