# Задание 2: Редактирование заявок ЕКЕВ

requests = ["ПК-1", "ПК-2", "ПК-3"]

# 1. Добавить "ПК-4" в конец
requests.append("ПК-4")

# 2. Вставить "Срочно" в начало
requests.insert(0, "Срочно")

# 3. Заменить "ПК-2" на "ПК-2 исправлен"
idx = requests.index("ПК-2")
requests[idx] = "ПК-2 исправлен"

# 4. Удалить "ПК-3" по значению
requests.remove("ПК-3")

# 5. Извлечь последний элемент через pop и вывести
last_item = requests.pop()
print("Извлечённый элемент:", last_item)

# Итоговый список
print("Оставшийся список:", requests)